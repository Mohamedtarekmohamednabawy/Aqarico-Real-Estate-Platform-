import api from './api';
import { cachedGet, invalidateGetCache } from './requestCache';

/**
 * Property service — handles all property-related API calls
 */
const propertyService = {
  /**
   * Get all properties with optional filters and pagination
   */
  getAll: async (params = {}, options = {}) => {
    return cachedGet('/properties', {
      params,
      ttl: options.ttl ?? 2 * 60 * 1000,
      force: options.force,
      signal: options.signal,
    });
  },

  /**
   * Get single property by ID
   */
  getById: async (id, options = {}) => {
    const response = await api.get(`/properties/${id}`, { signal: options.signal });
    return response.data;
  },

  /**
   * Get current user's listings
   */
  getMyProperties: async (options = {}) => {
    return cachedGet('/properties/my', {
      ttl: options.ttl ?? 60 * 1000,
      scope: 'user',
      force: options.force,
      signal: options.signal,
    });
  },

  /**
   * Get map pin data (lightweight)
   */
  getMapPins: async (options = {}) => {
    return cachedGet('/properties/map/pins', {
      ttl: options.ttl ?? 5 * 60 * 1000,
      force: options.force,
      signal: options.signal,
    });
  },

  /**
   * Create a new property listing
   * Uses FormData for image uploads
   */
  create: async (propertyData) => {
    const formData = new FormData();

    // Append simple fields
    const simpleFields = [
      'title', 'description', 'price', 'location', 'type',
      'category', 'area', 'bedrooms', 'bathrooms',
      'district', 'finish', 'yearBuilt', 'floor', 'levelWarning',
    ];

    simpleFields.forEach((field) => {
      if (propertyData[field] !== undefined && propertyData[field] !== null) {
        formData.append(field, propertyData[field]);
      }
    });

    // Append amenities as JSON string
    if (propertyData.amenities) {
      formData.append('amenities', JSON.stringify(propertyData.amenities));
    }

    // Append coordinates as JSON string
    if (propertyData.coordinates) {
      formData.append('coordinates', JSON.stringify(propertyData.coordinates));
    }

    // Append images (File objects or base64 strings)
    if (propertyData.images && propertyData.images.length > 0) {
      for (const image of propertyData.images) {
        if (image instanceof File) {
          formData.append('images', image);
        } else if (typeof image === 'string' && image.startsWith('data:')) {
          // Convert base64 to blob for upload
          const response = await fetch(image);
          const blob = await response.blob();
          formData.append('images', blob, 'image.jpg');
        }
      }
    }

    const res = await api.post('/properties', formData, {
      headers: { 'Content-Type': 'multipart/form-data' },
    });
    invalidateGetCache('/properties');
    return res.data;
  },

  /**
   * Update a property listing
   */
  update: async (id, propertyData) => {
    const formData = new FormData();

    const simpleFields = [
      'title', 'description', 'price', 'location', 'type',
      'category', 'area', 'bedrooms', 'bathrooms',
      'district', 'finish', 'yearBuilt', 'floor', 'levelWarning',
    ];

    simpleFields.forEach((field) => {
      if (propertyData[field] !== undefined && propertyData[field] !== null) {
        formData.append(field, propertyData[field]);
      }
    });

    if (propertyData.amenities) {
      formData.append('amenities', JSON.stringify(propertyData.amenities));
    }

    if (propertyData.coordinates) {
      formData.append('coordinates', JSON.stringify(propertyData.coordinates));
    }

    // Handle images: split into new (files/base64) and existing (URLs)
    if (propertyData.images && propertyData.images.length > 0) {
      const existingImages = [];
      for (const image of propertyData.images) {
        if (image instanceof File) {
          formData.append('images', image);
        } else if (typeof image === 'string' && image.startsWith('data:')) {
          const response = await fetch(image);
          const blob = await response.blob();
          formData.append('images', blob, 'image.jpg');
        } else if (typeof image === 'string' && image.startsWith('http')) {
          // It's an existing image URL
          // Skip placeholder images generated by the frontend
          if (!image.includes('placehold.co')) {
            existingImages.push(image);
          }
        }
      }
      formData.append('existingImages', JSON.stringify(existingImages));
    }

    const res = await api.put(`/properties/${id}`, formData, {
      headers: { 'Content-Type': 'multipart/form-data' },
    });
    invalidateGetCache('/properties');
    return res.data;
  },

  /**
   * Delete a property
   */
  delete: async (id) => {
    const response = await api.delete(`/properties/${id}`);
    invalidateGetCache('/properties');
    return response.data;
  },

  /**
   * Delete multiple properties
   */
  batchDelete: async (ids) => {
    const response = await api.post('/properties/batch-delete', { ids });
    invalidateGetCache('/properties');
    return response.data;
  },

  /**

   * Compare multiple properties
   */
  compare: async (propertyIds) => {
    const response = await api.post('/properties/compare', { propertyIds });
    return response.data;
  },

  /**
   * Get aggregated market statistics
   */
  getMarketStats: async (params = {}, options = {}) => {
    return cachedGet('/properties/stats/market', {
      params,
      ttl: options.ttl ?? 5 * 60 * 1000,
      force: options.force,
      signal: options.signal,
    });
  },
  getLocationStats: async (name, options = {}) => {
    return cachedGet(`/properties/stats/location/${encodeURIComponent(name)}`, {
      ttl: options.ttl ?? 5 * 60 * 1000,
      force: options.force,
      signal: options.signal,
    });
  },
};

export default propertyService;
